func newVerify() *cobra.Command {
	var project string
	var runtime, allowStart, allowPull bool
	var httpChecks []string
	cmd := &cobra.Command{Use: "verify", Short: "Verify a generated Compose proposal", Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if project == "" {
				return &ExitError{Code: 2, Err: errors.New("--project is required")}
			}
			if !runtime && (allowStart || allowPull || len(httpChecks) > 0) {
				return &ExitError{Code: 2, Err: errors.New("runtime options require --runtime")}
			}
			if allowPull && !allowStart {
				return &ExitError{Code: 2, Err: errors.New("--allow-pull requires --allow-start")}
			}
			report := verifyProject(cmd.Context(), project, runtime, allowStart, allowPull, httpChecks)
			data, err := json.MarshalIndent(report, "", "  ")
			if err != nil {
				return err
			}
			if _, err := cmd.OutOrStdout().Write(append(data, '\n')); err != nil {
				return err
			}
			if report.Outcome == verification.Failed {
				return &ExitError{Code: 4, Err: errors.New("verification failed; see JSON report")}
			}
			return nil
		}}
	cmd.Flags().StringVar(&project, "project", "", "Directory generated by eject generate")
	cmd.Flags().BoolVar(&runtime, "runtime", false, "Check the generated project with a local Docker runtime")
	cmd.Flags().BoolVar(&allowStart, "allow-start", false, "Explicitly authorize starting isolated local containers")
	cmd.Flags().BoolVar(&allowPull, "allow-pull", false, "Explicitly authorize Docker to download missing images during runtime verification")
	cmd.Flags().StringArrayVar(&httpChecks, "http-check", nil, "Runtime HTTP check service:port:/path (repeatable)")
	return cmd
}

func verifyProject(ctx context.Context, project string, runtime, allowStart, allowPull bool, httpChecks []string) verification.Report {
	mode := "static"
	if runtime {
		mode = "runtime"
	}
	report := verification.NewReport(mode)
	abs, err := filepath.Abs(project)
	if err != nil {
		report.Add("PROJECT_PATH", verification.Failed, "Invalid project path.")
		return report
	}
	if err := rejectSymlinkPath(abs); err != nil {
		report.Add("PROJECT_PATH", verification.Failed, "Project path contains a symlink or is inaccessible.")
		return report
	}
	plan, err := loadPlan(filepath.Join(abs, "plan.json"))
	if err != nil {
		report.Add("PLAN_READ", verification.Failed, "Versioned plan is missing, invalid or unsafe.")
		return report
	}
	bundle, err := generator.Build(ctx, plan)
	if err != nil {
		report.Add("PLAN_COHERENCE", verification.Failed, "Plan, resources and compatibility results are inconsistent.")
		return report
	}
	report = verification.Static(ctx, abs, bundle)
	report.Mode = mode
	if _, ok := bundle.Files["compose.yaml"]; ok && report.Outcome == verification.Passed {
		available := composeAvailable(ctx)
		if !available {
			report.Add("COMPOSE_SYNTAX", verification.Skipped, "Docker Compose is unavailable; generated YAML was parsed locally.")
		} else if err := validateComposeWithDocker(ctx, filepath.Join(abs, "compose.yaml")); err != nil {
			report.Add("COMPOSE_SYNTAX", verification.Failed, "Docker Compose rejected the generated configuration.")
		} else {
			report.Add("COMPOSE_SYNTAX", verification.Passed, "Docker Compose config accepted the generated configuration.")
		}
	} else {
		report.Add("COMPOSE_SYNTAX", verification.Skipped, "No eligible Compose file to validate, or static checks failed.")
	}
	if !runtime {
		report.Add("RUNTIME", verification.NotVerified, "Containers were not started.")
		return report
	}
	if report.Outcome == verification.Failed {
		report.Add("RUNTIME", verification.Skipped, "Runtime checks require successful static verification.")
		return report
	}
	if !allowStart {
		report.Add("RUNTIME_AUTHORIZATION", verification.Skipped, "Pass --allow-start to authorize starting local containers.")
		report.Outcome = verification.Skipped
		return report
	}
	if bundle.Status == "BLOCKED" {
		report.Add("RUNTIME", verification.Skipped, "Generation is blocked; no Compose service exists.")
		report.Outcome = verification.Skipped
		return report
	}
	if !composeAvailable(ctx) {
		report.Add("RUNTIME", verification.Skipped, "Docker Compose is unavailable.")
		report.Outcome = verification.Skipped
		return report
	}
	verification.Runtime(ctx, abs, bundle, allowPull, httpChecks, dockerEnvironment(), &report)
	return report
}

func composeAvailable(ctx context.Context) bool {
	docker, err := exec.LookPath("docker")
	if err != nil {
		return false
	}
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, docker, "compose", "version", "--short")
	cmd.Env = dockerEnvironment()
	return cmd.Run() == nil
}

func dockerEnvironment() []string {
	var env []string
	for _, key := range []string{"PATH", "APPDATA", "LOCALAPPDATA", "USERPROFILE", "PROGRAMDATA", "HOME", "DOCKER_CONFIG", "DOCKER_CLI_PLUGIN_EXTRA_DIRS"} {
		if value, ok := os.LookupEnv(key); ok {
			env = append(env, fmt.Sprintf("%s=%s", key, value))
		}
	}
	return env
}
